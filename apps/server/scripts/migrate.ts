#!/usr/bin/env npx tsx
import { NodeServices, NodeRuntime } from "@effect/platform-node"
import { FileSystem, Path } from "effect"
import {
  Array as EffectArray,
  Console,
  DateTime,
  Effect,
  pipe,
  Record,
  Schema,
  String as EffectString,
} from "effect"
import { ChildProcess, ChildProcessSpawner } from "effect/process"

const SCHEMA_FILE = "src/db/schema.sql"
const ATLAS_DIR = "src/db/migrations-sql"
const TURSO_DIR = "src/db/migrations-turso"
const EFFECT_DIR = "src/db/migrations-effect"
const ATLAS_ENV = "local"

/**
 * Everything after this line of `schema.sql` is Turso-only DDL, such as full-text search indexes.
 * Atlas can't parse it, so this script diffs it against `migrations-turso` itself.
 */
const TURSO_ONLY_MARKER = "-- TURSO ONLY"

class MigrationScriptError extends Schema.TaggedError<MigrationScriptError>()(
  "MigrationScriptError",
  {
    message: Schema.String,
  },
) {}

const MigrationNameArg = Schema.String.pipe(
  Schema.check(Schema.isMinLength(1)),
  Schema.check(Schema.isPattern(/^[a-z][a-z0-9_]*$/)),
  Schema.annotate({
    message: "Migration name must be lowercase alphanumeric with underscores",
  }),
)

const escapeForTemplateLiteral = (sql: string): string =>
  sql.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${")

const parseSqlStatements = (content: string): Array<string> =>
  content
    .split(";")
    .map((s) => s.trim())
    .filter(EffectString.isNonEmpty)

const generateEffectMigration = (
  statements: ReadonlyArray<string>,
  sources: ReadonlyArray<string>,
): string => {
  const escaped = statements.map(escapeForTemplateLiteral)

  return `// This file was autogenerated by \`migrate.ts\` based on ${sources.map((source) => `\`${source}\``).join(" and ")}
import { SqlClient } from "effect/sql"
import { Effect } from "effect"

export default Effect.gen(function*() {
  const sql = yield* SqlClient.SqlClient
${escaped.map((stmt) => `  yield* sql\`${stmt}\``).join("\n\n")}
})
`
}

const generateIndexFile = (migrationNames: ReadonlyArray<string>): string => {
  const imports = migrationNames
    .map((name) => {
      const safeName = name.replace(/\W/g, "_")
      return `import * as _${safeName} from "./${name}.js"`
    })
    .join("\n")

  const exports = migrationNames
    .map((name) => {
      const safeName = name.replace(/\W/g, "_")
      return `  "${name}": _${safeName}.default,`
    })
    .join("\n")

  return `// Auto-generated by migrate.ts - do not edit
${imports}

export const migrations = {
${exports}
} as const
`
}

const formatSchemaSQL = Effect.gen(function* () {
  yield* Effect.log("Formatting schema file")

  const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
  const command = ChildProcess.make("sql-formatter", ["--fix", SCHEMA_FILE], {
    stdout: "inherit",
    stderr: "inherit",
  })

  const result = yield* spawner.exitCode(command)

  if (result !== ChildProcessSpawner.ExitCode(0)) {
    yield* Effect.log("sql-formatter not found or failed, skipping formatting")
  }
})

/** Splits `schema.sql` into what Atlas diffs and the Turso-only DDL after `TURSO_ONLY_MARKER`. */
const readSchema = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const content = yield* fs.readFileString(SCHEMA_FILE)
  const markerIndex = content.indexOf(TURSO_ONLY_MARKER)

  return markerIndex === -1
    ? { atlas: content, turso: "" }
    : { atlas: content.slice(0, markerIndex), turso: content.slice(markerIndex) }
})

const withoutComments = (sql: string) => sql.replace(/--[^\n]*/g, "")
const normalizeStatement = (statement: string) => statement.replace(/\s+/g, " ").trim()

interface TursoIndex {
  readonly name: string
  readonly table: string
  readonly statement: string
}

const parseTursoIndexes = (sql: string) =>
  Effect.forEach(
    parseSqlStatements(withoutComments(sql)),
    (statement) => {
      const match = /^CREATE INDEX (\w+) ON (\w+) USING fts\b/i.exec(statement)

      return match?.[1] === undefined || match[2] === undefined
        ? Effect.fail(
            new MigrationScriptError({
              message: `Only full-text search indexes belong after "${TURSO_ONLY_MARKER}": ${statement}`,
            }),
          )
        : Effect.succeed<TursoIndex>({
            name: match[1],
            table: match[2],
            statement: normalizeStatement(statement),
          })
    },
    { concurrency: 1 },
  )

const listMigrationNames = (directory: string) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    if (!(yield* fs.exists(directory))) return []

    return pipe(
      yield* fs.readDirectory(directory),
      EffectArray.filter((file) => file.endsWith(".sql")),
      EffectArray.map((file) => file.replace(/\.sql$/, "")),
      EffectArray.sort(EffectString.Order),
    )
  })

/** The Turso indexes that applying every migration in `migrations-turso` leaves behind, by name. */
const appliedTursoIndexes = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path

  const statements = yield* Effect.forEach(
    yield* listMigrationNames(TURSO_DIR),
    (name) =>
      Effect.map(fs.readFileString(path.join(TURSO_DIR, `${name}.sql`)), (content) =>
        parseSqlStatements(withoutComments(content)),
      ),
    { concurrency: 1 },
  ).pipe(Effect.map(EffectArray.flatten))

  return EffectArray.reduce(
    statements,
    Record.empty<string, TursoIndex>(),
    (indexes, statement) => {
      const dropped = /^DROP INDEX IF EXISTS (\w+)$/i.exec(statement)?.[1]
      if (dropped !== undefined) return Record.remove(indexes, dropped)

      const created = /^CREATE INDEX (\w+) ON (\w+) USING fts\b/i.exec(statement)

      return created?.[1] === undefined || created[2] === undefined
        ? indexes
        : Record.set(indexes, created[1], {
            name: created[1],
            table: created[2],
            statement: normalizeStatement(statement),
          })
    },
  )
})

/** Atlas's migration version format: the UTC time as YYYYMMDDHHMMSS. */
const timestamp = Effect.map(DateTime.now, (now) =>
  DateTime.formatIso(now).replace(/\D/g, "").slice(0, 14),
)

/**
 * Writes the Turso-only DDL that brings the database from the previous migrations to `schema.sql`.
 * Atlas rebuilds tables to alter them, which drops their full-text search indexes,
 * so indexes on tables that a new Atlas migration drops are created again.
 */
const diffTurso = (input: { migrationName: string; newAtlasMigration: string | undefined }) =>
  Effect.gen(function* () {
    const fs = yield* FileSystem.FileSystem
    const path = yield* Path.Path

    const desired = yield* parseTursoIndexes((yield* readSchema).turso)
    const applied = yield* appliedTursoIndexes

    const rebuiltTables =
      input.newAtlasMigration === undefined
        ? []
        : parseSqlStatements(
            withoutComments(
              yield* fs.readFileString(path.join(ATLAS_DIR, `${input.newAtlasMigration}.sql`)),
            ),
          ).flatMap((statement) => {
            const table = /^DROP TABLE [`"]?(\w+)/i.exec(statement)?.[1]
            return table === undefined ? [] : [table]
          })

    const statements = [
      ...Record.values(applied)
        .filter((index) => !desired.some(({ name }) => name === index.name))
        .map((index) => `DROP INDEX IF EXISTS ${index.name}`),
      ...desired
        .filter(
          (index) =>
            applied[index.name]?.statement !== index.statement ||
            rebuiltTables.includes(index.table),
        )
        .flatMap((index) => [`DROP INDEX IF EXISTS ${index.name}`, index.statement]),
    ]

    if (EffectArray.isReadonlyArrayEmpty(statements)) {
      yield* Effect.log("Turso-only DDL is unchanged")
      return
    }

    const baseName = input.newAtlasMigration ?? `${yield* timestamp}_${input.migrationName}`
    yield* fs.makeDirectory(TURSO_DIR, { recursive: true })
    yield* fs.writeFileString(
      path.join(TURSO_DIR, `${baseName}.sql`),
      `${statements.map((statement) => `${statement};`).join("\n\n")}\n`,
    )
    yield* Effect.log(`Turso-only DDL -> ${TURSO_DIR}/${baseName}.sql`)
  })

const runAtlasDiff = (migrationName: string) =>
  Effect.gen(function* () {
    yield* Effect.log(`Running atlas migrate diff: ${migrationName}`)

    const fs = yield* FileSystem.FileSystem
    const spawner = yield* ChildProcessSpawner.ChildProcessSpawner
    const atlasSchema = yield* fs.makeTempFileScoped({ suffix: ".sql" })
    yield* fs.writeFileString(atlasSchema, (yield* readSchema).atlas)
    const before = yield* listMigrationNames(ATLAS_DIR)

    const command = ChildProcess.make(
      "npx",
      [
        "@ariga/atlas",
        "migrate",
        "diff",
        migrationName,
        "--env",
        ATLAS_ENV,
        "--to",
        `file://${atlasSchema}`,
      ],
      {
        stdout: "inherit",
        stderr: "inherit",
      },
    )

    const result = yield* spawner.exitCode(command)

    if (result !== ChildProcessSpawner.ExitCode(0)) {
      return yield* Effect.fail(
        new MigrationScriptError({ message: `Atlas exited with code ${result}` }),
      )
    }

    yield* Effect.log("Atlas migration generated successfully")
    return (yield* listMigrationNames(ATLAS_DIR)).find((name) => !before.includes(name))
  }).pipe(Effect.scoped)

/** Each migration runs its Atlas statements, then its Turso-only DDL. */
const convertMigrations = Effect.gen(function* () {
  const fs = yield* FileSystem.FileSystem
  const path = yield* Path.Path

  yield* fs.makeDirectory(EFFECT_DIR, { recursive: true })

  const atlasNames = yield* listMigrationNames(ATLAS_DIR)
  const tursoNames = yield* listMigrationNames(TURSO_DIR)
  const names = EffectArray.sort(EffectArray.union(atlasNames, tursoNames), EffectString.Order)

  if (EffectArray.isReadonlyArrayEmpty(names)) {
    yield* Effect.log("No SQL migration files found")
    return
  }

  const migrationNames = yield* Effect.forEach(
    names,
    (baseName) =>
      Effect.gen(function* () {
        const sources = [
          ...(atlasNames.includes(baseName) ? [path.join(ATLAS_DIR, `${baseName}.sql`)] : []),
          ...(tursoNames.includes(baseName) ? [path.join(TURSO_DIR, `${baseName}.sql`)] : []),
        ]

        const statements = yield* Effect.forEach(
          sources,
          (source) => Effect.map(fs.readFileString(source), (sql) => parseSqlStatements(sql)),
          { concurrency: 1 },
        ).pipe(Effect.map(EffectArray.flatten))

        if (EffectArray.isReadonlyArrayEmpty(statements)) {
          yield* Effect.log(`Skipping ${baseName} (no statements)`)
          return undefined
        }

        yield* fs.writeFileString(
          path.join(EFFECT_DIR, `${baseName}.ts`),
          generateEffectMigration(statements, sources),
        )
        yield* Effect.log(
          `${sources.join(" + ")} -> ${baseName}.ts (${statements.length} statements)`,
        )
        return baseName
      }),
    { concurrency: 1 },
  ).pipe(Effect.map((names) => names.filter((name): name is string => name !== undefined)))

  const indexContent = generateIndexFile(migrationNames)
  yield* fs.writeFileString(path.join(EFFECT_DIR, "index.ts"), indexContent)
  yield* Effect.log(`Generated index.ts with ${migrationNames.length} migrations`)
})

const program = Effect.gen(function* () {
  const args = yield* Effect.sync(() => process.argv.slice(2))

  if (EffectArray.isReadonlyArrayEmpty(args)) {
    yield* Console.error("Usage: npx tsx scripts/migrate.ts <migration_name>")
    yield* Console.error("Example: npx tsx scripts/migrate.ts add_users_table")
    return yield* Effect.fail(new MigrationScriptError({ message: "Missing migration name" }))
  }

  const migrationName = yield* Schema.decodeEffect(MigrationNameArg)(args[0]).pipe(
    Effect.mapError(
      () =>
        new MigrationScriptError({
          message: "Invalid migration name. Use lowercase alphanumeric with underscores.",
        }),
    ),
  )

  yield* formatSchemaSQL
  const newAtlasMigration = yield* runAtlasDiff(migrationName)
  yield* diffTurso({ migrationName, newAtlasMigration })
  yield* convertMigrations

  yield* Effect.log("\nMigration complete!")
})

pipe(program, Effect.provide(NodeServices.layer), NodeRuntime.runMain)
